/* --- low level --- */
#define CS_L()  HAL_GPIO_WritePin(LCD_CS_GPIO_Port,  LCD_CS_Pin,  GPIO_PIN_RESET)
#define CS_H()  HAL_GPIO_WritePin(LCD_CS_GPIO_Port,  LCD_CS_Pin,  GPIO_PIN_SET)
#define DC_CMD() HAL_GPIO_WritePin(LCD_DC_GPIO_Port, LCD_DC_Pin, GPIO_PIN_RESET)
#define DC_DAT() HAL_GPIO_WritePin(LCD_DC_GPIO_Port, LCD_DC_Pin, GPIO_PIN_SET)

static void lcd_write(const uint8_t *buf, uint16_t len) {
  HAL_SPI_Transmit(&hspi3, (uint8_t *)buf, len, HAL_MAX_DELAY);
}

static void lcd_cmd(uint8_t cmd) {
  DC_CMD();
  lcd_write(&cmd, 1);
}

static void lcd_data(uint8_t d) {
  DC_DAT();
  lcd_write(&d, 1);
}

static void lcd_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
  uint8_t b[4];
  lcd_cmd(0x2A);                 // column addr
  b[0]=x0>>8; b[1]=x0; b[2]=x1>>8; b[3]=x1; DC_DAT(); lcd_write(b,4);
  lcd_cmd(0x2B);                 // page addr
  b[0]=y0>>8; b[1]=y0; b[2]=y1>>8; b[3]=y1; DC_DAT(); lcd_write(b,4);
  lcd_cmd(0x2C);                 // memory write
}

void LCD_Backlight(uint8_t on) {
  HAL_GPIO_WritePin(LCD_BL_GPIO_Port, LCD_BL_Pin, on ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

void LCD_Init(void) {
  /* hardware reset */
  HAL_GPIO_WritePin(LCD_RST_GPIO_Port, LCD_RST_Pin, GPIO_PIN_RESET);
  HAL_Delay(20);
  HAL_GPIO_WritePin(LCD_RST_GPIO_Port, LCD_RST_Pin, GPIO_PIN_SET);
  HAL_Delay(120);

  CS_L();
  lcd_cmd(0x01); HAL_Delay(120);           // software reset
  lcd_cmd(0x11); HAL_Delay(120);           // sleep out

  lcd_cmd(0x3A); lcd_data(0x55);           // 16-bit pixel (RGB565)
  lcd_cmd(0x36); lcd_data(0xE8);           // MADCTL: landscape flipped 180 (MV|MX|MY|BGR)

  lcd_cmd(0xC0); lcd_data(0x23);           // power ctrl 1
  lcd_cmd(0xC1); lcd_data(0x10);           // power ctrl 2
  lcd_cmd(0xC5); lcd_data(0x3E); lcd_data(0x28); // vcom
  lcd_cmd(0xC7); lcd_data(0x86);

  lcd_cmd(0xB1); lcd_data(0x00); lcd_data(0x18); // frame rate
  lcd_cmd(0xB6); lcd_data(0x08); lcd_data(0x82); lcd_data(0x27);

  lcd_cmd(0x29); HAL_Delay(20);            // display on
  CS_H();

  LCD_Backlight(1);
  LCD_FillScreen(C_BLACK);
}

void LCD_FillRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
  if (x >= LCD_W || y >= LCD_H) return;
  if (x + w > LCD_W) w = LCD_W - x;
  if (y + h > LCD_H) h = LCD_H - y;

  uint8_t chunk[64 * 2];
  uint8_t hi = color >> 8, lo = color & 0xFF;
  for (int i = 0; i < 64; i++) { chunk[2*i] = hi; chunk[2*i+1] = lo; }

  CS_L();
  lcd_set_window(x, y, x + w - 1, y + h - 1);
  DC_DAT();
  uint32_t pixels = (uint32_t)w * h;
  while (pixels) {
    uint16_t n = pixels > 64 ? 64 : pixels;
    lcd_write(chunk, n * 2);
    pixels -= n;
  }
  CS_H();
}

void LCD_FillScreen(uint16_t color) {
  LCD_FillRect(0, 0, LCD_W, LCD_H, color);
}

void LCD_DrawChar(uint16_t x, uint16_t y, char c, uint16_t color, uint16_t bg, uint8_t size) {
  if (c < 0x20 || c > 0x7E) c = '?';
  const uint8_t *g = FONT5X7[c - 0x20];

  /* cell = 6 columns (5 glyph + 1 spacing) x 8 rows, scaled */
  for (uint8_t col = 0; col < 6; col++) {
    uint8_t bits = (col < 5) ? g[col] : 0x00;
    for (uint8_t row = 0; row < 8; row++) {
      uint16_t c16 = (bits & (1 << row)) ? color : bg;
      LCD_FillRect(x + col * size, y + row * size, size, size, c16);
    }
  }
}

void LCD_DrawString(uint16_t x, uint16_t y, const char *s, uint16_t color, uint16_t bg, uint8_t size) {
  while (*s) {
    LCD_DrawChar(x, y, *s++, color, bg, size);
    x += 6 * size;
  }
}

void LCD_DrawStringCentered(uint16_t y, const char *s, uint16_t color, uint16_t bg, uint8_t size) {
  uint16_t len = 0;
  for (const char *p = s; *p; p++) len++;
  uint16_t w = len * 6 * size;
  uint16_t x = (w >= LCD_W) ? 0 : (LCD_W - w) / 2;
  LCD_DrawString(x, y, s, color, bg, size);
}
